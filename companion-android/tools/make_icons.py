#!/usr/bin/env python3
"""The app's line icons from the HU's own: evaluates hu/ui/qml/Icons.qml (Qt, offscreen) and
writes each icon the app uses as an Android vector drawable, so both draw the same line art.

    python3 companion-android/tools/make_icons.py            # writes app/src/main/res/drawable/hu_*.xml
    python3 companion-android/tools/make_icons.py --check    # exit 1 if a drawable is out of date (CI)

Strokes are white with round caps and joins, 1.6 wide in the 24 x 24 box like Icon.qml; the
app tints them with the accent colour. Needs PySide6.
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
QML_DIR = ROOT / "hu" / "ui" / "qml"
OUT = ROOT / "companion-android" / "app" / "src" / "main" / "res" / "drawable"
# the icons the app shows (Icons.qml names)
USED = ["car", "fuel", "battery", "sun", "wrench", "warning", "info", "route", "flag", "bluetooth", "gear",
        "music", "speaker", "nav", "clock", "chevronRight", "back", "play", "pause", "next", "prev",
        "shuffle", "repeat", "mute", "list", "usb", "folder", "disc", "plus", "minus", "phone", "person"]
STROKE = 1.6


def icon_paths() -> dict[str, str]:
    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    from PySide6.QtCore import QUrl
    from PySide6.QtGui import QGuiApplication
    from PySide6.QtQml import QQmlComponent, QQmlEngine
    app = QGuiApplication.instance() or QGuiApplication(sys.argv[:1])   # noqa: F841 (Qt needs it)
    engine = QQmlEngine()
    engine.addImportPath(str(ROOT / "hu" / "ui" / "qml-demo"))      # the qml directory pulls in Sim and its backends
    comp = QQmlComponent(engine)
    names = ", ".join(f'"{n}": Icons.{n}' for n in USED)
    comp.setData(f'import QtQuick\nimport "."\nQtObject {{ property var paths: ({{{names}}}) }}'.encode(),
                 QUrl.fromLocalFile(str(QML_DIR / "make_icons.qml")))
    obj = comp.create()
    if obj is None:
        raise SystemExit("Icons.qml did not load: " + "; ".join(e.toString() for e in comp.errors()))
    paths = obj.property("paths")
    paths = paths.toVariant() if hasattr(paths, "toVariant") else paths
    missing = [n for n in USED if not paths.get(n)]
    if missing:
        raise SystemExit(f"not in Icons.qml: {', '.join(missing)}")
    return {n: paths[n].strip() for n in USED}


def drawable(name: str, path: str) -> str:
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by companion-android/tools/make_icons.py from hu/ui/qml/Icons.qml ({name}). Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">
    <path android:pathData="{path}"
        android:strokeColor="#FFFFFFFF" android:strokeWidth="{STROKE}" android:fillColor="#00000000"
        android:strokeLineCap="round" android:strokeLineJoin="round" />
</vector>
'''


def file_name(name: str) -> str:
    return "hu_" + "".join("_" + c.lower() if c.isupper() else c for c in name) + ".xml"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only check that the drawables are up to date")
    a = ap.parse_args()
    want = {file_name(n): drawable(n, p) for n, p in icon_paths().items()}
    stale = [f for f, text in want.items() if not (OUT / f).is_file() or (OUT / f).read_text() != text]
    extra = [f.name for f in OUT.glob("hu_*.xml") if f.name not in want]
    if a.check:
        if stale or extra:
            print(f"app icons out of date: {', '.join(stale + extra)} (run companion-android/tools/make_icons.py)")
            sys.exit(1)
        print(f"{len(want)} app icons up to date")
        return
    OUT.mkdir(parents=True, exist_ok=True)
    for f in extra:
        (OUT / f).unlink()
    for f, text in want.items():
        (OUT / f).write_text(text)
    print(f"wrote {len(want)} icons to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
